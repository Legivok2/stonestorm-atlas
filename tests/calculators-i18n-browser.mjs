import assert from 'node:assert/strict';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {root} from '../scripts/publication-plan.mjs';
import {createPreview} from '../scripts/serve-pages.mjs';

process.env.PLAYWRIGHT_BROWSERS_PATH??=path.join(root,'.integration/browser-qa/browsers');
const {chromium}=await import(pathToFileURL(path.join(root,'.integration/browser-qa/node_modules/playwright/index.mjs')));
const server=createPreview(path.join(root,'dist'));
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const base='http://127.0.0.1:'+server.address().port+'/stonestorm-atlas/';
const browser=await chromium.launch({headless:true});
try{
  for(const width of [375,1440]){
    const context=await browser.newContext({viewport:{width,height:900},reducedMotion:'reduce'});
    const page=await context.newPage(),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    page.on('console',message=>{if(message.type()==='warning'&&/Missing (Atlas|or outdated)/.test(message.text()))errors.push(message.text());});
    await page.goto(base+'#atlas/stat-limits',{waitUntil:'networkidle'});
    const original=await page.evaluate(()=>JSON.stringify({limits:StonestormStats.limits,critical:StonestormStats.critical,bonus:StonestormBonuses}));
    assert.match(await page.locator('#stat-calculator-title').innerText(),/stat/i);
    await page.locator('#stat-crit').fill('65,5');
    await page.locator('#stat-evade').fill('18.2');
    await page.locator('#reward-details > summary').click();
    await page.locator('#reward-equipment').fill('48,5');
    await page.locator('#critical-weapon-level').fill('54');
    await page.locator('[data-critical-band="5"][data-critical-tier="4"]').click();
    assert.equal(await page.locator('#stat-criticalBonus').inputValue(),'44,8');
    assert.equal(await page.locator('[data-effective="crit"]').innerText(),'50%');
    assert.equal(await page.locator('[data-excess="crit"]').innerText(),'15,5 százalékpont');
    assert.equal(await page.locator('[data-reward-result="effective"]').innerText(),'96,4%');
    await page.locator('.stat-limit-table details').first().locator('summary').click();
    await page.locator('#atlas-language [data-atlas-language=en]').click();
    assert.equal(await page.locator('#reward-details').getAttribute('open'),'');
    assert.equal(await page.locator('.stat-limit-table details').first().getAttribute('open'),'');
    assert.equal(await page.locator('#stat-crit').inputValue(),'65,5');
    assert.equal(await page.locator('#stat-evade').inputValue(),'18.2');
    assert.equal(await page.locator('#reward-equipment').inputValue(),'48,5');
    assert.equal(await page.locator('#critical-weapon-level').inputValue(),'54');
    assert.equal(await page.locator('[data-critical-band="5"][data-critical-tier="4"]').getAttribute('aria-pressed'),'true');
    assert.equal(await page.locator('[data-excess="crit"]').innerText(),'15.5 percentage points');
    assert.equal(await page.locator('[data-reward-result="effective"]').innerText(),'96.4%');
    assert.match(await page.locator('#atlas-screen').innerText(),/Critical chance|Damage reduction/);
    assert.doesNotMatch(await page.locator('#atlas-screen').innerText(),/Százalékpont|Felszerelések saját bónusza|Megerősített kliensadat/);
    await page.locator('#reward-equipment').fill('48.5');
    assert.equal(await page.locator('[data-reward-result="effective"]').innerText(),'96.4%');
    await page.locator('#stat-crit').fill('-1');
    assert.match(await page.locator('#stat-crit-error').innerText(),/finite/i);
    assert.match(await page.locator('#critical-results').innerText(),/soft.cap/i);
    await page.locator('#stat-criticalChance').fill('bad');
    assert.match(await page.locator('#stat-criticalChance-error').innerText(),/finite/i);
    await page.locator('#atlas-language [data-atlas-language=hu]').click();
    assert.equal(await page.locator('#stat-crit').inputValue(),'-1');
    assert.match(await page.locator('#stat-crit-error').innerText(),/véges/i);
    assert.equal(await page.locator('#stat-criticalChance').inputValue(),'bad');
    assert.match(await page.locator('#stat-criticalChance-error').innerText(),/véges/i);
    assert.equal(await page.locator('[data-reward-result="effective"]').innerText(),'96,4%');
    await page.evaluate(()=>location.hash='#atlas/bonuses');
    await page.locator('#bonus-pool').selectOption('jewel');
    await page.locator('#atlas-language [data-atlas-language=en]').click();
    assert.equal(await page.locator('#bonus-pool').inputValue(),'jewel');
    assert.equal(await page.locator('.bonus-catalog tbody tr').count(),20);
    assert.equal(await page.locator('.bonus-source-documentation tbody tr').count(),11);
    assert.match(await page.locator('#atlas-screen').innerText(),/Bonus sources and cap classification/);
    assert.doesNotMatch(await page.locator('#atlas-screen').innerText(),/Felszerelések saját bónusza|Kutatások|százalékpont/);
    await page.evaluate(()=>location.hash='#atlas/compare');
    await page.locator('#viewer-images [data-viewer-pick]').nth(0).click();
    await page.locator('#viewer-images [data-viewer-pick]').nth(1).click();
    assert.equal(await page.locator('.viewer-panels article').count(),2);
    const comparison=await page.locator('#viewer-comparison .atlas-table tbody').innerText();
    await page.locator('#atlas-language [data-atlas-language=hu]').click();
    assert.equal(await page.locator('.viewer-panels article').count(),2);
    assert.match(await page.locator('#viewer-comparison').innerText(),/ÖSSZEÁLLÍTÁS/);
    assert.equal((await page.locator('#viewer-comparison .atlas-table tbody').innerText()).replace(/[^\d−+]/g,''),comparison.replace(/[^\d−+]/g,''));
    await page.evaluate(()=>location.hash='#atlas/planner');
    await page.locator('#planner-level').fill('60');await page.locator('#planner-level').dispatchEvent('change');
    await page.locator('#planner-class').selectOption('warrior');
    await page.locator('#planner-compare').click();
    await page.locator('.planner-statistics details > summary').click();
    await page.locator('#atlas-language [data-atlas-language=en]').click();
    assert.equal(await page.locator('#planner-level').inputValue(),'60');
    assert.equal(await page.locator('#planner-class').inputValue(),'warrior');
    assert.equal(await page.locator('#planner-class option:checked').innerText(),'Warrior');
    assert.equal(await page.locator('.planner-character h4').innerText(),'Warrior');
    assert.equal(await page.locator('#planner-compare').getAttribute('aria-pressed'),'true');
    assert.equal(await page.locator('.planner-statistics details').getAttribute('open'),'');
    assert.equal(await page.evaluate(()=>JSON.stringify({limits:StonestormStats.limits,critical:StonestormStats.critical,bonus:StonestormBonuses})),original);
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`overflow at ${width}`);
    assert.deepEqual(errors,[]);
    console.log(`Chromium ${width}px: planner, limits, critical, rewards, comparison, state and decimals OK.`);
    await context.close();
  }
}finally{await browser.close();await new Promise(resolve=>server.close(resolve));}
